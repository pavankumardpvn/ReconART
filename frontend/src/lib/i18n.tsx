const ALL_TRANSLATIONS: Record<LangCode, Translations> = { en, es, pt, hi };

interface I18nContextType {
  region: Region;
  lang: LangCode;
  t: (key: string) => string;
  setRegion: (code: string) => void;
}

const defaultRegion = REGIONS[0];

const I18nContext = createContext<I18nContextType>({
  region: defaultRegion,
  lang: "en",
  t: (key) => key,
  setRegion: () => {},
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [region, setRegionState] = useState<Region>(defaultRegion);

  useEffect(() => {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved) {
        const found = REGIONS.find((r) => r.code === saved);
        if (found) setRegionState(found);
      }
    } catch { /* ignore */ }
  }, []);

  const setRegion = useCallback((code: string) => {
    const found = REGIONS.find((r) => r.code === code);
    if (found) {
      setRegionState(found);
      try { localStorage.setItem(STORAGE_KEY, code); } catch { /* ignore */ }
    }
  }, []);

  const t = useCallback(
    (key: string) => ALL_TRANSLATIONS[region.lang]?.[key] || ALL_TRANSLATIONS.en[key] || key,
    [region.lang]
  );

  return (
    <I18nContext.Provider value={{ region, lang: region.lang, t, setRegion }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  return useContext(I18nContext);
}
